// EVENT_FLOW generator (P4 registry-driven variant)
// Reads domains/shared/event_ids.hpp (single source of truth) and scans
// domains/*.reducer.hpp + scripts/*.lua to map producers -> consumers.
// Emits docs/pods/EVENT_FLOW.md + event-flow.json. EXACT, not heuristic:
// every fact in the registry appears; emissions missing from the registry
// are reported as errors (undeclared-producer gate).
import { readFileSync, writeFileSync, readdirSync } from 'fs';
import path from 'path';

const ROOT = new URL('..', import.meta.url).pathname;
const DOMAINS = path.join(ROOT, 'domains');
const OUT_MD = path.join(ROOT, 'docs/pods/EVENT_FLOW.md');
const OUT_JSON = path.join(ROOT, 'docs/pods/event-flow.json');

// ---- 1. parse the registry -------------------------------------------------
const regSrc = readFileSync(
    path.join(DOMAINS, 'shared/event_ids.hpp'), 'utf8');
const registry = [];
for (const m of regSrc.matchAll(
        /\{\s*FactId::([A-Z_]+),\s*"([A-Z_]+)",\s*"(\w+)"\s*\}/g)) {
    registry.push({ id: m[1], name: m[2], producer: m[3] });
}
if (registry.length === 0) {
    console.error('ERROR: no facts parsed from event_ids.hpp'); process.exit(1);
}

// ---- 2. scan consumers (any pod referencing the fact name) ------------------
const consumers = {};   // fact -> Set(pod)
let undeclared = [];
for (const pod of readdirSync(DOMAINS)) {
    const dir = path.join(DOMAINS, pod);
    let files;
    try { files = readdirSync(dir).filter((f) => f.endsWith('.hpp')); }
    catch { continue; }
    for (const f of files) {
        if (f.includes('.plan.')) continue;
        const src = readFileSync(path.join(dir, f), 'utf8');
        // matrix typed events
        for (const m of src.matchAll(/MatrixEventType::([A-Z_]+)/g)) {
            ((consumers[m[1]] ??= new Set()).add('matrix'));
            ((consumers[m[1]] ??= new Set()).add(`${pod}`));
        }
        // progression typed events
        for (const m of src.matchAll(/ProgressionEventType::([A-Z_]+)/g)) {
            (consumers[m[1]] ??= new Set()).add('progression');
        }
        // powerup + environment typed events
        for (const m of src.matchAll(/PowerupEventType::([A-Z_]+)/g)) {
            (consumers[m[1]] ??= new Set()).add('powerups');
        }
    }
}

// ---- 3. undeclared-producer gate --------------------------------------------
const registeredNames = new Set(registry.map((r) => r.name));
const podNames = new Set(readdirSync(DOMAINS));
for (const key of Object.keys(consumers)) {
    if (!registeredNames.has(key) && !podNames.has(key))
        undeclared.push(key);
}

// ---- 4. emit markdown --------------------------------------------------------
let md = [];
md.push('# EVENT FLOW MAP (C++ Tetris) - auto-generated from event registry');
md.push('');
md.push('> Generated by scripts/generate-event-flow.mjs from');
md.push('> domains/shared/event_ids.hpp. Facts registered: **' +
        registry.length + '**');
if (undeclared.length) {
    md.push('');
    md.push('> WARNING undeclared emissions found: ' +
            undeclared.join(', ') + ' - add them to the registry.');
}
md.push('');
md.push('## Fact -> producer -> consumers');
md.push('');
md.push('| Fact | Producer | Referenced by |');
md.push('| --- | --- | --- |');
for (const f of registry) {
    const refs = new Set(consumers[f.name] ?? []);
    refs.delete(f.producer);
    md.push("| `" + f.name + "` | " + f.producer + " | " +
            [...refs].sort().map((c) => '`' + c + '`').join(', '));
}
writeFileSync(OUT_MD, md.join('\n') + '\n');

// ---- 5. machine-readable JSON ------------------------------------------------
writeFileSync(OUT_JSON, JSON.stringify({
    generatedFrom: 'domains/shared/event_ids.hpp',
    facts: registry.map((f) => ({
        ...f,
        referencedBy: [...(consumers[f.name] ?? [])].sort(),
    })),
}, null, 2));

console.log(`EVENT_FLOW: ${registry.length} registered facts;` +
    (undeclared.length ? ` UNDECLARED: ${undeclared.join(',')}` : ' all declared'));
