// EVENT_FLOW generator (C++ variant) - scans domains/*.reducer.hpp for
// MatrixEventType::X emissions, builds docs/pods/EVENT_FLOW.md matrix.
import { readFileSync, writeFileSync, readdirSync } from 'fs';
import path from 'path';

const ROOT = new URL('..', import.meta.url).pathname;
const DOMAINS = path.join(ROOT, 'domains');
const OUT_MD = path.join(ROOT, 'docs/pods/EVENT_FLOW.md');
const OUT_JSON = path.join(ROOT, 'docs/pods/event-flow.json');

const pods = {};
for (const pod of readdirSync(DOMAINS)) {
  const dir = path.join(DOMAINS, pod);
  let files;
  try { files = readdirSync(dir).filter((f) => f.endsWith('.hpp')); }
  catch { continue; }
  for (const f of files) {
    if (f.includes('.plan.') || f.includes('.action.')) continue;
    const rel = `domains/${pod}/${f}`;
    const src = readFileSync(path.join(dir, f), 'utf8');
    for (const m of src.matchAll(/MatrixEventType::([A-Z_]+)/g)) {
      ((pods[pod] ??= {})[m[1]] ??= []).push(rel);
    }
  }
}

const allFacts = [...new Set(Object.values(pods).flatMap((e) => Object.keys(e)))].sort();
let md = [];
md.push('# EVENT FLOW MAP (C++ Tetris) - auto-generated');
md.push('');
md.push('> Generated by scripts/generate-event-flow.mjs. Regenerate after');
md.push('> adding emissions or traps. Facts mapped: **' + allFacts.length + '**');
md.push('');
md.push('## Fact -> consumer matrix');
md.push('');
md.push('| Fact | Pod(s) referencing |');
md.push('| --- | --- |');
for (const ev of allFacts) {
  const refs = [];
  for (const [pod, evs] of Object.entries(pods)) {
    if (evs[ev]) refs.push(pod);
  }
  md.push(`| \`${ev}\` | ${refs.map((c) => '\`' + c + '\`').join(', ')} |`);
}
writeFileSync(OUT_MD, md.join('\n') + '\n');
writeFileSync(OUT_JSON, JSON.stringify({ pods }, null, 2));
console.log('EVENT_FLOW (C++):', allFacts.length, 'facts mapped');
